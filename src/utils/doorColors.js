import { colorText } from "@/utils/crmLabels";

// Образцы цвета для кружков-свотчей по текстовому названию цвета из CRM
// («Тёплый песочный», «Graphite Grey», «Цвет Глины»…). В CRM нет HEX-кодов,
// поэтому оттенок приблизительный — в интерфейсе это явно подписано.
// Правила проверяются по порядку: более конкретные — выше.

const RULES = [
  [/(белый с золотом|white.*gold)/i, "#f1ece0"],
  [/(морск|ocean|teal)/i, "#2f5b5e"],
  [/(тёмно.?син|темно.?син|глубокий син|deep blue|navy)/i, "#24364f"],
  [/(син|blue)/i, "#3f5f86"],
  [/(баклажан)/i, "#4a2f3d"],
  [/(терракот)/i, "#a65a3e"],
  [/(красн|red)/i, "#8e2f2a"],
  [/(ярко.?зел)/i, "#4f8a3c"],
  [/(серо.?зел)/i, "#7a857a"],
  [/(олив)/i, "#6f7150"],
  [/(зел|green)/i, "#4f6b52"],
  [/(глин|clay)/i, "#a8846a"],
  [/(шоколад)/i, "#4a3226"],
  [/(венге)/i, "#3b2c24"],
  [/(орех)/i, "#6e4d34"],
  [/(коричн|brown)/i, "#6a4b36"],
  [/(кофе с молоком)/i, "#b39a7f"],
  [/(капучино)/i, "#a88b70"],
  [/(светлый дуб)/i, "#c9a77c"],
  [/(дуб|древес|wood|oak)/i, "#a97d52"],
  [/(тёмно.?сер|темно.?сер|глубокий сер|graphite|графит)/i, "#4a4a48"],
  [/(дымчат|stone)/i, "#8e8b85"],
  [/(светло.?сер)/i, "#c9c8c3"],
  [/(сер|grey|gray)/i, "#9a9894"],
  [/(пудров)/i, "#e3cfc6"],
  [/(перламутр)/i, "#ece8e1"],
  [/(бежево.?песоч|песоч|sand)/i, "#d6bf98"],
  [/(светло.?беж)/i, "#e7dac4"],
  [/(беж)/i, "#dcc8a8"],
  [/(слонов|айвори|ivory)/i, "#f0e9d8"],
  [/(кремов|молоч|cream)/i, "#efe5d0"],
  [/(бел|white)/i, "#f6f5f1"],
  [/(черн|black)/i, "#232325"],
];

const FALLBACK = "#cfc6b8";

export function colorSwatch(name = "") {
  for (const [re, hex] of RULES) {
    if (re.test(name)) return hex;
  }
  return FALLBACK;
}

// Подпись цвета для интерфейса: без служебного «цвет» и на языке сайта (см. utils/crmLabels).
export function colorLabel(name = "") {
  return colorText(name);
}
